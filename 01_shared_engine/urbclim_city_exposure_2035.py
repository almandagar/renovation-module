"""Evidence-locked spatial 2035 UrbClim city exposure sidecar (RESEARCH ONLY).

Reads provider Geotiffs only. Does NOT synthesize 8760 hours, convert
published 2031-2040 decadal averages to a 2035 weather chronology, predict
indoor comfort, or equate provider emissions scenarios with PI/PAS/HDE.

Zonal grids must be generated by a separate, documented spatial join from the
canonical city-building or population map, aligned to the original UrbClim
rasters; zero IDs denote unassigned grid cells. For source download, see
https://zenodo.org/records/13361538 and the metadata readme.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
from pathlib import Path
from typing import Mapping
import numpy as np
import rasterio

INDICATORS={
    'nighttime_uhi_c': ('T2M_daily_mean_min_topography','degC'),
    'warm_nights_20_days_per_year': ('T2M_nightover20','days/year'),
    'heatwave_days_per_year': ('heatwave_days','days/year'),
    'cooling_degree_hours_year': ('cooling_degree_hours','degreeC-hours/year'),
    'wbgt_hot_hours_28_per_year': ('WBGT_hourover28','hours/year'),
}
PROVIDER_SCENARIOS={'CurPol':'Current Policies','GS':'Delayed Action / Gradual Strengthening','SP':'Shifting Pathways'}
PROVIDER_STATISTICS={'ensmean','enspctl05','enspctl95'}
REFERENCE='https://zenodo.org/records/13361538'


def digest(path:Path)->str:
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for c in iter(lambda:f.read(1<<20),b''):h.update(c)
    return h.hexdigest()


def _read(path:Path):
    with rasterio.open(path) as s:
        if s.count!=1 or s.crs is None:
            raise ValueError('GeoTIFF requires exactly one band and an explicit CRS')
        v=s.read(1,masked=True)
        a=np.asarray(v.filled(np.nan),dtype=float)
        if s.nodata is not None:
            a[a==s.nodata]=np.nan
        return a,s.transform,s.crs,s.width,s.height,s.nodata


def _weighted_percentile(v,w,p):
    ix=np.argsort(v);vv=v[ix];ww=w[ix];cs=np.cumsum(ww)
    return float(vv[min(int(np.searchsorted(cs, p*cs[-1],side='left')),len(vv)-1)])


def aggregate_city_rasters(*, city:str, member_inputs:Mapping[str,Path], zone_grid:Path,
    population_grid:Path|None, provider_scenario:str,statistic:str, period:str='2031-2040',
    provenance:str='VITO_UrbClim_Souverijns_2026',source_release:str='zenodo_13361538'):
    """Return zonal exposure indicators from *real* co-registered provider maps.

    The zone-grid 0 is unassigned; all positive integer IDs are retained.
    If population_grid is None, cells are area weighted, NOT population weighted.
    Do not interpret map indicators as hourly weather deltas or effects of renovation.
    """
    if not city or not provenance or not source_release: raise ValueError('Missing source identity')
    if provider_scenario not in PROVIDER_SCENARIOS:
        raise ValueError('Use independent provider scenario CurPol, GS, or SP; not PI/PAS/HDE')
    if statistic not in PROVIDER_STATISTICS:raise ValueError('Invalid climate ensemble statistic')
    if period not in ('2011-2020','2021-2030','2031-2040'):
        raise ValueError('Research adapter permits only documented nearby decades')
    if not member_inputs:raise ValueError('No source raster inputs')
    bad=set(member_inputs)-set(INDICATORS)
    if bad:raise ValueError('Unknown indicator(s): '+repr(sorted(bad)))
    z,t,crs,width,height,_=_read(Path(zone_grid))
    if not np.isfinite(z).all() or np.any(z<0) or not np.all(z==np.floor(z)):
        raise ValueError('Zone grid must contain nonnegative integer identifiers (0 unassigned)')
    w=None
    if population_grid:
        w,wt,wc,ww,wh,_=_read(Path(population_grid))
        if (wt,wc,ww,wh)!=(t,crs,width,height):raise ValueError('Population grid not aligned with source-zone grid')
        if np.any(w[np.isfinite(w)]<0):raise ValueError('Negative population weight')
    else:
        w=np.ones_like(z)
    layers={};origins={}
    for k,path in member_inputs.items():
        path=Path(path)
        # Assert the claimed indicator is named in the provider file. Filename alone
        # is never sufficient to verify its source; checksums also returned.
        if INDICATORS[k][0] not in path.stem:
            raise ValueError('Source filename does not name requested indicator: '+k)
        # Zenodo provider names the decade as YYYY_YYYY, while the API's
        # canonical period is YYYY-YYYY. Accept both spellings, preserve the
        # canonical metadata and fail closed for a genuinely different decade.
        if not any(decade in path.stem for decade in (period,period.replace('-','_'))):
            raise ValueError('Source raster filename missing scope '+period)
        for token in (provider_scenario,statistic):
            if token not in path.stem:raise ValueError('Source raster filename missing scope '+token)
        v,vt,vc,vw,vh,_=_read(path)
        if (vt,vc,vw,vh)!=(t,crs,width,height):raise ValueError('Unaligned indicator raster '+k)
        layers[k]=v
        origins[k]={'sha256':digest(path),'name':path.name,'provider_indicator':INDICATORS[k][0], 'unit':INDICATORS[k][1]}
    rows=[]
    for zi in sorted(set(z[z>0].astype(int))):
        region=(z==zi)
        for k,v in layers.items():
            ok=region&np.isfinite(v)&np.isfinite(w)&(w>0)
            if not ok.any():continue
            x=v[ok];wt=w[ok]
            if k!='nighttime_uhi_c' and np.any(x<0):raise ValueError('Negative published count/duration indicator')
            rows.append({'city':city,'zone_id':int(zi),'indicator':k,
              'unit':INDICATORS[k][1], 'period':period,
              'provider_scenario':provider_scenario,'ensemble_statistic':statistic,
              'cell_count':int(ok.sum()), 'included_weight':float(wt.sum()),
              'weight_basis':'population' if population_grid else 'equal_grid_cell',
              'mean':float(np.average(x,weights=wt)),'p90':_weighted_percentile(x,wt,.9),
              'min':float(x.min()),'max':float(x.max()),
              'output_status':'RESEARCH_CITY_EXPOSURE_NOT_BUILDING_COMFORT'})
    if not rows: raise ValueError('No overlapping valid city/zone source raster cells')
    return {'schema':'urbclim-city-exposure/1','status':'RESEARCH_ONLY_NOT_RUNTIME',
      'source':REFERENCE,'source_release':source_release,'source_method':provenance,
      'city':city,'provider_scenario':provider_scenario,'provider_period':period,
      'provider_ensemble_statistic':statistic,'zone_grid_sha256':digest(zone_grid),
      'population_grid_sha256':digest(population_grid) if population_grid else None,
      'inputs':origins,'rows':rows,
      'limits':['2031-2040 represents a decade, not exact 2035 hourly meteorology',
        'Provider emissions pathways are NOT PI/PAS/HDE',
        'Urban morphology is held static in the published climate projections',
        'Not indoor comfort, not causal renovation effects, not an hourly EPW correction',
        'Do not add provider urban UHI to already urban baseline temperature',
        'No local model calibration or climate-model bias verification from maps alone']}


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--city',required=True);p.add_argument('--zone-tif',type=Path,required=True)
    p.add_argument('--population-tif',type=Path)
    p.add_argument('--scenario',required=True,choices=sorted(PROVIDER_SCENARIOS))
    p.add_argument('--statistic',default='ensmean',choices=sorted(PROVIDER_STATISTICS))
    p.add_argument('--period',default='2031-2040')
    p.add_argument('--indicator',action='append',required=True,help='semantic_key=/path/to/provider_indicator.tif')
    p.add_argument('--out',required=True,type=Path)
    a=p.parse_args();inputs={}
    for s in a.indicator:
        k,sep,v=s.partition('=')
        if not sep or not v:raise ValueError('Invalid indicator=path argument')
        inputs[k]=Path(v)
    output=aggregate_city_rasters(city=a.city,member_inputs=inputs,zone_grid=a.zone_tif,
        population_grid=a.population_tif,provider_scenario=a.scenario,statistic=a.statistic,period=a.period)
    a.out.parent.mkdir(parents=True,exist_ok=True)
    a.out.write_text(json.dumps(output,indent=2,allow_nan=False)+'\n',encoding='utf-8')
    print(json.dumps({'status':output['status'],'n_rows':len(output['rows']),'out':str(a.out)}))
if __name__=='__main__':main()
